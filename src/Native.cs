    internal sealed class Screenish
    {
        public readonly IntPtr Handle;
        public readonly Rectangle Bounds;
        public readonly Rectangle WorkArea;
        public readonly float Scale;

        public Screenish(IntPtr handle, Rectangle bounds, Rectangle work, float scale)
        {
            Handle = handle;
            Bounds = bounds;
            WorkArea = work;
            Scale = scale <= 0 ? 1 : scale;
        }
    }
