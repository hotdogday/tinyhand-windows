        public static void EnableDpiAwareness()
        {
            try
            {
                // DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2
                if (SetProcessDpiAwarenessContext(new IntPtr(-4)))
                {
                    return;
                }
            }
            catch (EntryPointNotFoundException)
            {
            }
            try
            {
                SetProcessDPIAware();
            }
            catch
            {
            }
        }

        /// <summary>The monitor under a point, in physical pixels.</summary>
        public static Screenish MonitorAt(Point p)
        {
            IntPtr mon = MonitorFromPoint(new POINT(p.X, p.Y), 2 /* MONITOR_DEFAULTTONEAREST */);
            MONITORINFO mi = new MONITORINFO();
            mi.cbSize = Marshal.SizeOf(typeof(MONITORINFO));
            GetMonitorInfo(mon, ref mi);
            uint dx = 96, dy = 96;
            try
            {
                GetDpiForMonitor(mon, 0, out dx, out dy);
            }
            catch
            {
            }
            return new Screenish(mon, mi.rcMonitor.ToRectangle(), mi.rcWork.ToRectangle(), dx / 96f);
        }

        public static Rectangle WindowRect(IntPtr hwnd)
        {
            RECT r;
            GetWindowRect(hwnd, out r);
            return r.ToRectangle();
        }
